#!/bin/sh
# old-vs-new close-up comparison sheets for every weapon: wsheets.sh <old glb dir> [names...]
OLD=$1; shift
cd "$(dirname "$0")"
R="270,4,0.62,0,0.04,0.13;90,4,0.62,0,0.04,0.13;300,22,0.30,0,0.07,0.02;60,18,0.30,0,0.07,0.43"
for n in ${@:-ak74m ak74m_optic ak12 pkm rpg7 rpg22 rpg22_carried grenade_f1 grenade_rgd5}; do
  case $n in
    pkm) V="270,4,0.82,0,0.04,0.27;90,4,0.82,0,0.04,0.27;300,25,0.34,0,0.08,0.10;55,18,0.34,0,0.07,0.72";;
    rpg7) V="270,4,0.8,0,0.07,-0.02;90,4,0.8,0,0.07,-0.02;300,22,0.38,0,0.09,-0.15;50,18,0.38,0,0.08,0.38";;
    rpg22) V="90,5,0.75,0,0.07,-0.03;270,5,0.75,0,0.07,-0.03;300,25,0.32,0,0.11,-0.12;60,20,0.32,0,0.11,0.30";;
    rpg22_carried) V="90,5,0.65,0,0,0;270,5,0.65,0,0,0;300,25,0.3,0,0.03,-0.2;60,20,0.3,0,0.03,0.2";;
    grenade_*) V="60,12,0.34,0.013,0.012,0;200,20,0.34,0.013,0.012,0;300,65,0.3,0.013,0.012,0;120,-15,0.34,0.013,0.012,0";;
    *) V=$R;;
  esac
  ./pvw.sh "$OLD/$n.glb" "assets/soldiers/$n.glb" "previews/weapons/cmp_$n.png" "views=$V&h=800" | tr '\n' ' '; echo " $n"
done
